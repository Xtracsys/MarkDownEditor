# Hardened build + package pipeline.
#
# Why -nopackage + manual assembly: wails' final self-sign step races with
# iCloud's file provider (this checkout lives in a synced Desktop folder),
# which attaches xattrs to freshly written files and makes codesign fail —
# silently leaving a stale artifact behind on earlier runs. Here the binary is
# compiled without packaging, the .app bundle is assembled from the static
# template in build/darwin/static/, scrubbed, and signed by this script. Every
# artifact is verified to contain the unique build stamp before it is shipped.
#
# Usage: scripts/build-all.sh [version]
set -euo pipefail

VERSION="${1:-0.1.6}"
STAMP="$(date -u +%Y%m%d%H%M%S)"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO"
WAILS="${WAILS:-$HOME/go/bin/wails}"
APP="build/bin/xtracsys-editor.app"
BIN="$APP/Contents/MacOS/xtracsys-editor"

echo "==> version $VERSION, stamp $STAMP"
echo "==> building frontend bundle"
( cd frontend && npm run build >/dev/null )
# iCloud's file provider re-creates deleted files in synced folders; junk
# duplicates would be embedded by go:embed and bloat/mislead the binary.
JUNK=$(find frontend/dist -name "* 2.*" -o -name "* 3.*" 2>/dev/null | head -1)
if [ -n "$JUNK" ]; then
  echo "    scrubbing file-provider conflict copies:"
  find frontend/dist \( -name "* 2.*" -o -name "* 3.*" \) -delete
fi
cat > internal/app/buildstamp_gen.go <<EOF
// Code generated by scripts/build-all.sh; DO NOT EDIT.
package app

const GeneratedAppVersion = "$VERSION"
const GeneratedBuildStamp = "$STAMP"
EOF
xattr -cr build 2>/dev/null || true
xattr -cr frontend/dist 2>/dev/null || true
rm -rf build/bin
mkdir -p dist build/bin

echo "==> compiling darwin/universal (nopackage)"
LOG="$(mktemp)"
if ! "$WAILS" build -platform darwin/universal -s -skipbindings -nopackage >"$LOG" 2>&1; then
  echo "FATAL: compile failed:"; tail -6 "$LOG"; exit 1
fi
grep -q "Built " "$LOG" || { echo "FATAL: compile did not complete:"; tail -6 "$LOG"; exit 1; }
stamp_ok() { grep -aq "$STAMP" "$1" 2>/dev/null; }
for i in 1 2 3 4 5; do stamp_ok build/bin/xtracsys-editor && break; sleep 1; done
stamp_ok build/bin/xtracsys-editor || { echo "FATAL: bare binary lacks stamp"; exit 1; }
echo "    bare binary verified (stamp $STAMP)"

echo "==> assembling and signing $APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp build/darwin/static/Info.plist "$APP/Contents/Info.plist"
cp build/darwin/static/PkgInfo "$APP/Contents/PkgInfo"
cp build/darwin/icon.icns "$APP/Contents/Resources/iconfile.icns"  # name must match CFBundleIconFile
plutil -replace CFBundleShortVersionString -string "$VERSION" "$APP/Contents/Info.plist"
plutil -replace CFBundleVersion -string "$VERSION" "$APP/Contents/Info.plist"
cp build/bin/xtracsys-editor "$BIN"
chmod +x "$BIN"
xattr -cr "$APP" 2>/dev/null || true
codesign --force --sign - "$APP" >/dev/null 2>&1
codesign --verify "$APP"
echo "    signed"

echo "==> packaging macOS DMG"
rm -f "dist/xtracsys-editor-$VERSION-macos-universal.dmg"
scripts/make-dmg.sh "$APP" "dist/xtracsys-editor-$VERSION-macos-universal.dmg" >/dev/null
MNT="$(mktemp -d)"
hdiutil attach "dist/xtracsys-editor-$VERSION-macos-universal.dmg" -mountpoint "$MNT" -nobrowse -quiet
for i in 1 2 3 4 5; do stamp_ok "$MNT/xtracsys-editor.app/Contents/MacOS/xtracsys-editor" && break; sleep 1; done
stamp_ok "$MNT/xtracsys-editor.app/Contents/MacOS/xtracsys-editor" || {
  hdiutil detach "$MNT" -quiet; echo "FATAL: DMG binary lacks stamp"; exit 1
}
hdiutil detach "$MNT" -quiet
rmdir "$MNT" 2>/dev/null || true
echo "    DMG verified"

echo "==> compiling windows/amd64"
LOG="$(mktemp)"
if ! "$WAILS" build -platform windows/amd64 -s -skipbindings -nopackage >"$LOG" 2>&1; then
  echo "FATAL: windows compile failed:"; tail -6 "$LOG"; exit 1
fi
grep -q "Built " "$LOG" || { echo "FATAL: windows compile incomplete"; tail -6 "$LOG"; exit 1; }
for i in 1 2 3 4 5; do stamp_ok build/bin/xtracsys-editor.exe && break; sleep 1; done
stamp_ok build/bin/xtracsys-editor.exe || { echo "FATAL: stale windows binary"; exit 1; }
( cd build/bin && rm -f "../../dist/xtracsys-editor-$VERSION-windows-x64.zip" && zip -q -r "../../dist/xtracsys-editor-$VERSION-windows-x64.zip" xtracsys-editor.exe )
echo "    windows zip verified"

echo "==> compiling NSIS installer"
makensis -V2 -DVERSION="$VERSION" build/windows/installer/xtracsys-editor.nsi >/dev/null
echo "    installer written"

( cd dist && shasum -a 256 "xtracsys-editor-$VERSION"-*.dmg "xtracsys-editor-$VERSION"-*.zip "xtracsys-editor-$VERSION"-*.exe > SHA256SUMS.txt )
echo "==> artifacts:"
ls -la dist/
echo "==> stamp: $STAMP  (About dialog and Startup diagnostics include version $VERSION)"
