import { chromium } from "@playwright/test";
const browser = await chromium.launch();
const page = await browser.newPage();
page.on("console", (m) => console.log("CONSOLE[" + m.type() + "]:", m.text().slice(0, 200)));
page.on("pageerror", (e) => console.log("PAGE-ERROR:", (e && e.stack || String(e)).slice(0, 600)));
await page.goto("http://127.0.0.1:34122/?e2e=1");
await page.waitForFunction(() => !!window.__xe);
await page.evaluate(() => { void window.__xe.app.openPaths(["/tmp/e2e-docs/demo.md"]); });
await page.waitForTimeout(600);
await page.locator(".cm-content").click();
await page.keyboard.type("DBG2 ");
await page.waitForTimeout(6000);
console.log("--- reloading (simulating crash) ---");
await page.reload();
await page.waitForFunction(() => !!window.__xe);
await page.waitForTimeout(2500);
const modalText = await page.locator(".modal").textContent().catch(() => "NO MODAL");
console.log("MODAL:", modalText.slice(0, 120));
await browser.close();
